-- ------------------------------------------------------------
-- 3.1 Webhook Trigger History Table
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS WEBHOOK_TRIGGER_HISTORY (
    TRIGGER_HISTORY_ID BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    JOB_NAME VARCHAR(100) NOT NULL COMMENT 'Job 이름',
    JOB_EXECUTION_ID BIGINT NULL COMMENT 'Spring Batch Job Execution ID',
    TRACE_ID VARCHAR(50) NOT NULL COMMENT '추적 ID (UUID)',
    TRIGGER_SOURCE VARCHAR(50) NOT NULL COMMENT '트리거 소스 (webhook, quartz, manual)',
    API_KEY_NAME VARCHAR(50) NULL COMMENT '사용된 API Key 이름',
    CLIENT_IP VARCHAR(45) NULL COMMENT '클라이언트 IP 주소',
    REQUEST_PARAMETERS TEXT NULL COMMENT '요청 파라미터 (JSON)',
    STATUS VARCHAR(20) NOT NULL COMMENT '상태 (ACCEPTED, COMPLETED, FAILED)',
    ERROR_MESSAGE VARCHAR(2500) NULL COMMENT '에러 메시지',
    TRIGGERED_AT DATETIME(6) NOT NULL COMMENT '트리거 시간',
    COMPLETED_AT DATETIME(6) NULL COMMENT '완료 시간',
    CREATED_AT DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UPDATED_AT DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci
COMMENT='Webhook Job 트리거 이력';

-- ------------------------------------------------------------
-- 3.2 Job Notification History Table
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS JOB_NOTIFICATION_HISTORY (
    NOTIFICATION_ID BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    JOB_EXECUTION_ID BIGINT NOT NULL COMMENT 'Spring Batch Job Execution ID',
    JOB_NAME VARCHAR(100) NOT NULL COMMENT 'Job 이름',
    NOTIFICATION_TYPE VARCHAR(30) NOT NULL COMMENT '알림 유형 (EMAIL, SLACK, WEBHOOK, SMS)',
    NOTIFICATION_EVENT VARCHAR(30) NOT NULL COMMENT '알림 이벤트 (STARTED, COMPLETED, FAILED, STOPPED)',
    RECIPIENT VARCHAR(500) NOT NULL COMMENT '수신자 (이메일, 슬랙 채널, URL 등)',
    SUBJECT VARCHAR(500) NULL COMMENT '제목',
    CONTENT TEXT NULL COMMENT '내용',
    STATUS VARCHAR(20) NOT NULL COMMENT '발송 상태 (PENDING, SENT, FAILED)',
    ERROR_MESSAGE VARCHAR(2500) NULL COMMENT '발송 실패 시 에러 메시지',
    RETRY_COUNT INT NOT NULL DEFAULT 0 COMMENT '재시도 횟수',
    SENT_AT DATETIME(6) NULL COMMENT '발송 시간',
    CREATED_AT DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UPDATED_AT DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci
COMMENT='Job 알림 발송 이력';

